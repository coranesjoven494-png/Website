const revealObserver = new IntersectionObserver(entries => entries.forEach(entry => { if (entry.isIntersecting) entry.target.classList.add('visible'); }), { threshold: .08 });
document.querySelectorAll('.reveal').forEach(element => revealObserver.observe(element));

const navLinks = [...document.querySelectorAll('.nav-link')];
const sectionObserver = new IntersectionObserver(entries => entries.forEach(entry => {
  if (entry.isIntersecting) navLinks.forEach(link => link.classList.toggle('active', link.getAttribute('href') === `#${entry.target.id}`));
}), { rootMargin: '-25% 0px -65% 0px' });
document.querySelectorAll('main section[id]').forEach(section => sectionObserver.observe(section));

const menuToggle = document.getElementById('menuToggle');
const nav = document.getElementById('navLinks');
menuToggle.addEventListener('click', () => { const isOpen = nav.classList.toggle('open'); menuToggle.setAttribute('aria-expanded', String(isOpen)); menuToggle.textContent = isOpen ? '×' : '☰'; });
navLinks.forEach(link => link.addEventListener('click', () => { nav.classList.remove('open'); menuToggle.setAttribute('aria-expanded', 'false'); menuToggle.textContent = '☰'; }));

window.addEventListener('scroll', () => { const scrollable = document.documentElement.scrollHeight - window.innerHeight; document.getElementById('progressBar').style.width = `${(window.scrollY / scrollable) * 100}%`; }, { passive: true });
